function icon(name: string, rows: string[]): PixelMap { return coded(rows, `play.${name}`); }

/** A map's rows in the direction's codes, so that it can be redrawn with some tones swapped. */
function rowsOf(m: PixelMap): string[] {
  const out: string[] = [];
  for (let y = 0; y < m.h; y++) {
    let r = '';
    for (let x = 0; x < m.w; x++) { const c = m.cells[y * m.w + x]; r += c === NONE ? '.' : CODE[c]; }
    out.push(r);
  }
  return out;
}

/** A copy of a map with tones swapped: `swap` is pairs of codes, `from` then `to`. */
function swapped(src: PixelMap | string[], swap: string, name: string): PixelMap {
  const rows = Array.isArray(src) ? src : rowsOf(src);
  const to = new Map<string, string>();
  for (let i = 0; i < swap.length; i += 2) to.set(swap[i], swap[i + 1]);
  return icon(name, rows.map((r) => [...r].map((ch) => to.get(ch) ?? ch).join('')));
}

